// 結婚の起きやすさの年齢の形（18歳から55歳まで、相対値）
export function marryShape(sex) {
  const peak = sex === 'm' ? 30 : 28;
  const out = [];
  for (let a = 18; a <= 55; a++) {
    const d = (a - peak) / (sex === 'm' ? 5.5 : 4.8);
    out.push(Math.exp(-d * d / 2) + (a > peak ? 0.04 : 0));
  }
  return out;
}
